import {mkdir, readdir, writeFile} from 'node:fs/promises';

const root = new URL('../', import.meta.url);

async function filesIn(directory, accepts, optional = false) {
  try {
    return (await readdir(new URL(directory, root), {withFileTypes: true}))
      .filter(entry => entry.isFile() && !entry.name.startsWith('.') && accepts(entry.name))
      .map(entry => entry.name)
      .sort((a, b) => a.localeCompare(b, undefined, {numeric: true}));
  } catch (error) {
    if (optional && error.code === 'ENOENT') return [];
    throw error;
  }
}

const gallery = await filesIn('images/optimized/gallery/', name => name.endsWith('.webp'));
const thumbnails = await filesIn('images/optimized/thumbnails/', name => name.endsWith('.webp'));
if (gallery.length !== thumbnails.length || gallery.some((name, index) => name !== thumbnails[index])) {
  throw new Error('Optimized gallery photos and thumbnails must have matching filenames.');
}
const music = (await filesIn('audio/', name => /\.(?:mp3|m4a|ogg|wav|MP3|M4A|OGG|WAV)$/.test(name) && name !== 'placeholder.wav', true))
  .sort((a, b) => a.localeCompare(b));

const imports = [];
const exports = [];
function addRecord(name, directory, files) {
  const entries = files.map((file, index) => {
    const identifier = `${name}${index}`;
    imports.push(`import ${identifier} from ${JSON.stringify(`../../${directory}/${file}`)};`);
    // Preserve import.meta.glob's original keys so the existing numeric gallery
    // ordering, thumbnail lookup and music selection remain unchanged.
    return `  ${JSON.stringify(`../${directory}/${file}`)}: ${identifier},`;
  });
  exports.push(`export const ${name}: Record<string, string> = {\n${entries.join('\n')}\n};`);
}
addRecord('imageModules', 'images/optimized/gallery', gallery);
addRecord('thumbnailModules', 'images/optimized/thumbnails', thumbnails);
addRecord('musicFiles', 'audio', music);

const output = new URL('src/generated/', root);
await mkdir(output, {recursive: true});
await writeFile(new URL('assets.ts', output), `// Generated by scripts/generate-assets.mjs. Do not edit.\n${imports.join('\n')}\n\n${exports.join('\n\n')}\n`);
console.log(`Generated asset imports: ${gallery.length} gallery photos, ${thumbnails.length} thumbnails and ${music.length} music files.`);
